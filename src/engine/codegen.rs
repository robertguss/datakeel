use crate::cli::CodegenTarget;
use crate::contract::{Contract, LogicalType};
use std::fmt::Write;

pub fn generate(contract: &Contract, target: CodegenTarget, schema: Option<&str>) -> String {
    match target {
        CodegenTarget::Postgres => generate_postgres_ddl(contract, schema),
        CodegenTarget::Pydantic => generate_pydantic_v2(contract),
    }
}

fn generate_postgres_ddl(contract: &Contract, schema: Option<&str>) -> String {
    let mut out = String::new();
    let table_ref = match schema {
        Some(s) if !s.trim().is_empty() => format!("{}.{}", quote_pg(s.trim()), quote_pg(&contract.table)),
        _ => quote_pg(&contract.table),
    };

    let _ = writeln!(
        out,
        "-- Generated by datakeel from contract '{}' (v{})",
        contract.name, contract.version
    );
    if let Some(ref desc) = contract.description {
        let _ = writeln!(out, "-- {}", desc.replace('\n', " "));
    }
    let _ = writeln!(out, "CREATE TABLE IF NOT EXISTS {table_ref} (");

    let pk_cols: Vec<&String> = contract
        .columns
        .iter()
        .filter(|(_, c)| c.primary_key)
        .map(|(n, _)| n)
        .collect();

    let mut lines: Vec<String> = Vec::new();
    for (col_name, col) in &contract.columns {
        let pg_type = col
            .physical_type
            .as_deref()
            .unwrap_or_else(|| col.logical_type.default_postgres_type());

        let mut parts = vec![format!("    {} {}", quote_pg(col_name), pg_type)];
        if col.required || col.primary_key {
            parts.push("NOT NULL".to_string());
        }
        if col.unique && !col.primary_key {
            parts.push("UNIQUE".to_string());
        }

        let mut checks = Vec::new();
        if let Some(min) = col.min {
            checks.push(format!("{} >= {}", quote_pg(col_name), format_num(min)));
        }
        if let Some(max) = col.max {
            checks.push(format!("{} <= {}", quote_pg(col_name), format_num(max)));
        }
        if let Some(ref vals) = col.allowed_values
            && !vals.is_empty()
        {
            let quoted: Vec<String> = vals
                .iter()
                .map(|v| format!("'{}'", v.replace('\'', "''")))
                .collect();
            checks.push(format!("{} IN ({})", quote_pg(col_name), quoted.join(", ")));
        }
        if !checks.is_empty() {
            parts.push(format!("CHECK ({})", checks.join(" AND ")));
        }

        lines.push(parts.join(" "));
    }

    if !pk_cols.is_empty() {
        let quoted_pks: Vec<String> = pk_cols.iter().map(|c| quote_pg(c)).collect();
        lines.push(format!("    PRIMARY KEY ({})", quoted_pks.join(", ")));
    }

    let _ = writeln!(out, "{}", lines.join(",\n"));
    let _ = writeln!(out, ");");

    // Emit column comments for documentation parity
    for (col_name, col) in &contract.columns {
        if let Some(ref desc) = col.description {
            let escaped = desc.replace('\'', "''");
            let _ = writeln!(
                out,
                "COMMENT ON COLUMN {table_ref}.{} IS '{escaped}';",
                quote_pg(col_name)
            );
        }
    }

    out
}

fn generate_pydantic_v2(contract: &Contract) -> String {
    let mut out = String::new();
    let class_name = to_pascal_case(&contract.name);

    let needs_date = contract
        .columns
        .values()
        .any(|c| c.logical_type == LogicalType::Date);
    let needs_datetime = contract
        .columns
        .values()
        .any(|c| c.logical_type == LogicalType::Timestamp);
    let needs_any = contract
        .columns
        .values()
        .any(|c| matches!(c.logical_type, LogicalType::Array | LogicalType::Object | LogicalType::Any));
    let needs_literal = contract
        .columns
        .values()
        .any(|c| c.allowed_values.as_ref().is_some_and(|v| !v.is_empty()));

    let _ = writeln!(
        out,
        "# Generated by datakeel from contract '{}' (v{})",
        contract.name, contract.version
    );
    let _ = writeln!(out, "from __future__ import annotations\n");

    if needs_date || needs_datetime {
        let mut dt_imports = Vec::new();
        if needs_date {
            dt_imports.push("date");
        }
        if needs_datetime {
            dt_imports.push("datetime");
        }
        let _ = writeln!(out, "from datetime import {}", dt_imports.join(", "));
    }

    let mut typing_imports = Vec::new();
    if needs_any {
        typing_imports.push("Any");
    }
    if needs_literal {
        typing_imports.push("Literal");
    }
    if !typing_imports.is_empty() {
        let _ = writeln!(out, "from typing import {}", typing_imports.join(", "));
    }

    let _ = writeln!(out, "from pydantic import BaseModel, ConfigDict, Field\n\n");
    let _ = writeln!(out, "class {class_name}(BaseModel):");
    if let Some(ref desc) = contract.description {
        let _ = writeln!(out, "    \"\"\"{}\"\"\"\n", desc.replace("\"\"\"", "\\\"\\\"\\\""));
    }
    if contract.strict {
        let _ = writeln!(out, "    model_config = ConfigDict(extra=\"forbid\")\n");
    }

    if contract.columns.is_empty() {
        let _ = writeln!(out, "    pass");
    } else {
        for (col_name, col) in &contract.columns {
            let base_type = if let Some(ref vals) = col.allowed_values {
                if !vals.is_empty() {
                    let lits: Vec<String> = vals
                        .iter()
                        .map(|v| format!("{v:?}"))
                        .collect();
                    format!("Literal[{}]", lits.join(", "))
                } else {
                    col.logical_type.python_type().to_string()
                }
            } else {
                col.logical_type.python_type().to_string()
            };

            let py_type = if col.required || col.primary_key {
                base_type
            } else {
                format!("{base_type} | None")
            };

            let mut field_args: Vec<String> = Vec::new();
            if !(col.required || col.primary_key) {
                field_args.push("default=None".to_string());
            }
            if let Some(min) = col.min {
                field_args.push(format!("ge={}", format_num(min)));
            }
            if let Some(max) = col.max {
                field_args.push(format!("le={}", format_num(max)));
            }
            if let Some(min_len) = col.min_length {
                field_args.push(format!("min_length={min_len}"));
            }
            if let Some(max_len) = col.max_length {
                field_args.push(format!("max_length={max_len}"));
            }
            if let Some(ref pat) = col.pattern {
                field_args.push(format!("pattern=r{pat:?}"));
            }
            if let Some(ref desc) = col.description {
                field_args.push(format!("description={desc:?}"));
            }

            if field_args.is_empty() {
                let _ = writeln!(out, "    {col_name}: {py_type}");
            } else if field_args.len() == 1 && field_args[0] == "default=None" {
                let _ = writeln!(out, "    {col_name}: {py_type} = None");
            } else {
                let _ = writeln!(
                    out,
                    "    {col_name}: {py_type} = Field({})",
                    field_args.join(", ")
                );
            }
        }
    }

    out
}

fn quote_pg(ident: &str) -> String {
    let simple = !ident.is_empty()
        && ident
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
        && !ident.starts_with(|c: char| c.is_ascii_digit());
    if simple {
        ident.to_string()
    } else {
        format!("\"{}\"", ident.replace('"', "\"\""))
    }
}

fn format_num(v: f64) -> String {
    if v.fract() == 0.0 && v.abs() < 1e15 {
        format!("{:.0}", v)
    } else {
        format!("{v}")
    }
}

fn to_pascal_case(s: &str) -> String {
    let out: String = s
        .split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                Some(first) => {
                    let mut chunk = first.to_ascii_uppercase().to_string();
                    chunk.push_str(&chars.as_str().to_ascii_lowercase());
                    chunk
                }
                None => String::new(),
            }
        })
        .collect();
    if out.is_empty() {
        "Record".to_string()
    } else {
        out
    }
}
